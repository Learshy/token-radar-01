  function riskFor(p) {
    var c = (p.category || '').toLowerCase();
    var name = p.name;
    if (c.indexOf('lend') >= 0 || c.indexOf('cdp') >= 0 || c.indexOf('collateral') >= 0) return 'Lending risk is a bad-debt event or a frozen market: keep the position small, watch the borrow rate, and unwind by repaying any borrow first, then withdrawing the supply in one transaction.';
    if (c.indexOf('dex') >= 0 || c.indexOf('yield') >= 0 || c.indexOf('leveraged farm') >= 0 || c.indexOf('farm') >= 0) return "Liquidity risk is impermanent loss and a thin pool: exit by removing the whole position in one transaction when the pool's depth falls or the position passes its hold.";
    if (c.indexOf('bridge') >= 0) return "Bridge risk is a delayed or stuck transfer: keep the receipt, wait one full day, and use only the protocol's own support channel before bridging again.";
    if (c.indexOf('staking') >= 0 || c.indexOf('restak') >= 0) return 'Staking risk is a slashing event or a long unbonding: exit by starting the unbonding early and never staking more than you can leave locked.';
    if (c.indexOf('perpetual') >= 0 || c.indexOf('derivative') >= 0) return 'Perpetual risk is liquidation: keep leverage low, and exit by closing the hedge before the margin ratio falls.';
    if (c.indexOf('prediction') >= 0) return 'Prediction risk is a market resolving against you: exit by closing the position before resolution instead of holding it to the end.';
    if (c.indexOf('curator') >= 0 || c.indexOf('allocator') >= 0 || c.indexOf('curation') >= 0) return 'Vault risk is one bad curator call: spread across two vaults, and exit by redeeming the shares for the underlying asset in one transaction.';
    if (c.indexOf('stable') >= 0) return 'Stable-asset risk is a depeg: exit by redeeming for the underlying asset while the peg still holds.';
    if (c.indexOf('rwa') >= 0) return 'RWA risk is an off-chain default: exit by redeeming the yield asset for its underlying before the next distribution date.';
    if (c.indexOf('insurance') >= 0) return 'Cover risk is an unpaid claim: keep the policy documents, and exit by letting the cover lapse at expiry instead of renewing it.';
    if (c.indexOf('basis') >= 0) return 'Basis risk is a funding-rate flip: exit by closing the position when the funding rate turns against you for a full week.';
    if (c.indexOf('payment') >= 0 || c.indexOf('card') >= 0) return 'Payment risk is a frozen balance: keep only the funds you plan to spend in the ' + name + ' balance, and withdraw the rest to your own wallet.';
    if (c.indexOf('index') >= 0) return 'Index risk is one bad constituent: exit by selling the index token back in one transaction when its composition changes.';
    if (c.indexOf('chain') >= 0) return 'Chain risk is a halted chain: keep the position small, and exit by bridging the funds back as soon as the chain resumes.';
    if (c.indexOf('governance') >= 0) return 'Governance risk is a vote that changes the rules: exit by withdrawing the deposit if a passed proposal cuts the rewards.';
    return 'Exit risk is a frozen contract or a paused withdrawal: keep the position small enough to lose, and unwind in one transaction as soon as withdrawals slow.';
  }
  function stepText(step) {
    var s = step.text + ' Cost: ' + step.cost + '. Time: ' + step.time + '.';
    if (s.length > 600) s = s.slice(0, 596) + '...';
    if (s.length < 20) s = s + " Hold the position and check the protocol's own page.";
    return s;
  }
  function farmSteps(p) {
    var chain = chainOf(p);
    var secondChain = secondChainOf(p);
    var capital = capitalFor(p);
    var hold = holdDaysFor(p.age_days);
    return [
      { text: 'Use a fresh wallet that holds only the funds you plan to farm, and keep its seed phrase offline.', cost: 'under $3 of gas for the first transaction', time: '5 minutes' },
      { text: actionFor(p, capital, chain), cost: '$' + capital + ' of capital and about $' + (capital >= 150 ? 8 : 4) + ' of gas', time: '15 minutes to set up' },
      { text: deepenFor(p, capital, chain, secondChain), cost: 'about $' + (capital >= 150 ? 4 : 2) + ' of gas', time: '10 minutes' },
      { text: 'Make one qualifying action each week, such as ' + weeklyFor(p) + '.', cost: 'about $2 of gas a week', time: '10 minutes a week' },
      { text: 'Hold the position for at least ' + hold + ' days so the activity is counted in more than one snapshot.', cost: 'the $' + capital + ' stays in the position', time: hold + ' days' },
      { text: riskFor(p) + ' Claim only from the link the protocol itself publishes, and never pay anyone to claim.', cost: 'no fee to check', time: '10 minutes to review the exit' },
      { text: 'Write the wallet, the dates and every transaction in a farm log so you can repeat the position or unwind it.', cost: 'nothing but the log', time: '5 minutes' }
    ].map(stepText);
  }

  function readHash() {
    var hash = window.location.hash.replace(/^#/, '');
    if (!hash) return;
    var params = new URLSearchParams(hash);
    if (params.get('q')) state.q = params.get('q');
    if (params.get('p')) state.selected = params.get('p');
    if (params.get('category')) state.category = params.get('category');
    if (params.get('sort')) state.sort = params.get('sort');
    if (params.get('tab')) state.tab = params.get('tab');
  }
  function writeHash() {
    var params = new URLSearchParams();
    if (state.q) params.set('q', state.q);
    if (state.category !== 'all') params.set('category', state.category);
    if (state.selected) params.set('p', state.selected);
    if (state.sort !== 'implied') params.set('sort', state.sort);
    if (state.tab !== 'pre-token') params.set('tab', state.tab);
    var next = params.toString();
    if (next) window.history.replaceState(null, '', '#' + next);
    else window.history.replaceState(null, '', window.location.pathname + window.location.search);
  }

  function rows() {
    var q = state.q.trim().toLowerCase();
    return DATA.rows.filter(function (r) {
      if (state.category !== 'all' && r.category !== state.category) return false;
      if (!q) return true;
      var hay = [r.name, r.slug, r.category, (r.chains || []).join(' ')].join(' ').toLowerCase();
      return hay.indexOf(q) >= 0;
    });
  }
  function sortedRows(list) {
    var key = state.sort;
    return list.slice().sort(function (a, b) {
      var av, bv;
      if (key === 'rising') { av = a.rising; bv = b.rising; }
      else if (key === 'name') { av = a.name.toLowerCase(); bv = b.name.toLowerCase(); }
      else if (key === 'tvl') { av = a.tvl_usd; bv = b.tvl_usd; }
      else if (key === 'growth') { av = a.change_7d === null ? -Infinity : a.change_7d; bv = b.change_7d === null ? -Infinity : b.change_7d; }
      else if (key === 'age') { av = a.age_days === null ? Infinity : a.age_days; bv = b.age_days === null ? Infinity : b.age_days; }
      else { av = a.implied_value_usd; bv = b.implied_value_usd; }
      if (av < bv) return -state.dir;
      if (av > bv) return state.dir;
      return a.slug < b.slug ? -1 : a.slug > b.slug ? 1 : 0;
    });
  }

